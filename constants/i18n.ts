export const getLanguageFromLocale = (locale: string): LanguageCode => {
  const code = locale.split('-')[0].split('_')[0].toLowerCase() as LanguageCode;
  const supported = SUPPORTED_LANGUAGES.map(l => l.code);
  return supported.includes(code) ? code : 'en';
};

export const getLanguageInfo = (code: LanguageCode): Language => {
  return SUPPORTED_LANGUAGES.find(l => l.code === code) || SUPPORTED_LANGUAGES[1];
};
