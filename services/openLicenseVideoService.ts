// ─── STATS ────────────────────────────────────────────────────────────────────
export function getOpenCatalogStats() {
  const total = OPEN_LICENSE_CATALOG.length;
  const ready = OPEN_LICENSE_CATALOG.filter(v => v.ingest_status === 'ready').length;
  const pendingIngest = OPEN_LICENSE_CATALOG.filter(v => v.ingest_status === 'not_started').length;
  const rightsReview = OPEN_LICENSE_CATALOG.filter(v => v.rights_status === 'rights_review').length;
  const verified = OPEN_LICENSE_CATALOG.filter(v => v.rights_status === 'verified').length;
  const byLicense = OPEN_LICENSE_CATALOG.reduce((acc, v) => {
    acc[v.license] = (acc[v.license] || 0) + 1;
    return acc;
  }, {} as Record<string, number>);
  const ccBy = byLicense['cc_by'] || 0;
  const ccBySa = byLicense['cc_by_sa'] || 0;
  const publicDomain = (byLicense['public_domain'] || 0) + (byLicense['us_government'] || 0) + (byLicense['cc0'] || 0);
  const commercialSafe = OPEN_LICENSE_CATALOG.filter(v => v.commercial_use_allowed && v.rights_status === 'verified').length;

  return { total, ready, pendingIngest, rightsReview, verified, byLicense, ccBy, ccBySa, publicDomain, commercialSafe };
}

